from enum import Enum, IntFlag


class AggressionLevels(Enum):
	PASSIVE = 0			# Never attacks
	VENGEFUL = 1		# Hit & run
	RAMPAGE = 2			# Attacks until defeated or left alone


class Directions(IntFlag):
	EAST = 0x1
	NORTH = 0x2
	WEST = 0x3
	SOUTH = 0x4
	NORTHEAST = NORTH | EAST
	NORTHWEST = NORTH | WEST
	SOUTHEAST = SOUTH | EAST
	SOUTHWEST = SOUTH | WEST


class EquipmentSlots(IntFlag):
	FEET = 0x000001
	SHINS = 0x000002
	LEGS = 0x000004
	WAIST = 0x000008
	ABDOMEN = 0x000010
	TORSO = 0x000020
	SHOULDERS = 0x000040
	ARMS = 0x000080
	FOREARMS = 0x000100
	GLOVES = 0x000200
	LEFT_HELD = 0x000400
	RIGHT_HELD = 0x000800
	LEFT_RING = 0x001000
	RIGHT_RING = 0x002000
	AMULET = 0x004000
	CAPE = 0x008000
	NECK = 0x010000
	FACE = 0x020000
	LEFT_EAR = 0x040000
	RIGHT_EAR = 0x080000
	HEAD = 0x100000
	TWO_HANDED = 0x200000
	EITHER_HELD = LEFT_HELD | RIGHT_HELD
	LEFT_SIDE = LEFT_EAR | LEFT_RING | LEFT_HELD
	RIGHT_SIDE = RIGHT_EAR | RIGHT_RING | RIGHT_HELD
	EITHER_SIDE = LEFT_SIDE | RIGHT_SIDE


class Pronouns(Enum):
	SUBJECTIVE = 'subjective'
	OBJECTIVE = 'objective'
	POSSESSIVE = 'possessive'
	ADJECTIVE = 'adjective'
	REFLEXIVE = 'reflexive'


class Seasons(Enum):
	BRIGHTBLOOM = 0
	SOLSTIME = 1
	LEAFGLOW = 2
	FROSTFALL = 3


class TimesOfDay(IntFlag):
	DAWN = 0x1
	MORNING = 0x2
	NOON = 0x4
	AFTERNOON = 0x8
	EVENING = 0x10
	DUSK = 0x20
	NIGHT = 0x40


class TimePartitions(IntFlag):
	AURORAL = TimesOfDay.DAWN
	DIURNAL = TimesOfDay.DAWN | TimesOfDay.MORNING | TimesOfDay.NOON | TimesOfDay.AFTERNOON | TimesOfDay.EVENING
	CREPUSCULAR = TimesOfDay.EVENING | TimesOfDay.DUSK
	NOCTURNAL = TimesOfDay.DUSK | TimesOfDay.NIGHT
	CATHEMERAL = AURORAL | DIURNAL | CREPUSCULAR | NOCTURNAL
